import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const input = process.argv[2] || "http://127.0.0.1:8766/api/source-coverage/boards";
const output = resolve(here, "snapshot.js");
const states = ["ok", "degraded", "failing", "stale", "paused", "never"];

const text = /^https?:\/\//.test(input)
  ? await fetch(input).then(response => {
      if (!response.ok) throw new Error(`Snapshot request failed (${response.status})`);
      return response.text();
    })
  : await readFile(resolve(input), "utf8");
const payload = JSON.parse(text);

if (!Array.isArray(payload.providers)) {
  throw new Error("Snapshot is missing its providers array.");
}

const compact = {
  computed_at: payload.computed_at || null,
  totals: payload.totals || {},
  providers: payload.providers.map(provider => ({
    source: String(provider.source),
    board_count: Number(provider.board_count) || provider.boards?.length || 0,
    err_count: Number(provider.err_count) || 0,
    // One token per board: state index followed by base-36 role coverage.
    // Board identity stays live-only; the offline skyline retains exact visual data.
    packed: (provider.boards || []).map(board => {
      const state = Math.max(0, states.indexOf(board.state));
      const coverage = Math.max(0, Number(board.coverage) || 0);
      return `${state}${coverage.toString(36)}`;
    }).join(","),
  })),
};

await writeFile(
  output,
  `/* Generated by build-snapshot.mjs; refresh before sharing the standalone mockup. */\nwindow.FEED_CITY_SNAPSHOT=${JSON.stringify(compact)};\n`,
  "utf8",
);
console.log(`Wrote ${output}`);
